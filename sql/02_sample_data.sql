--
-- 数据说明：
--   doc.id 与块 id 都是固定写死的 UUIDv7，共 27 个块；
--   block_type：1 标题，2 普通文字；
--   segments 中 color 缺省表示普通文字颜色，取值仅 red / blue / green / yellow 四种；
--   普通文字块的 text 是 segments 各片段拼接后的纯文本，两处内容保持一致。
--
-- 块之间是一棵树，parent_id 记父块（根的父为 '0'），sort_index 记在同一个父块下的序号：
--   * 一级标题「示例文档」挂在根下；
--   * 四个二级标题挂在它下面，各自再带自己的三级标题与正文；
--   * 文字块挂在它上方最近的标题下，哪一级都算，所以最后一段正文的父是六级标题；
--   * 第二个块的父是一级标题而不是根：文字块与下一级标题地位平等，共用同一套序号。
-- =============================================================

